import { v, type Infer } from "convex/values";

/**
 * Shared validators. The schema, the mutations and (later) the AI action all
 * use these, so a trip tree has exactly one shape everywhere.
 */

export const activityCategory = v.union(
  v.literal("sightseeing"),
  v.literal("food"),
  v.literal("lodging"),
  v.literal("transport"),
  v.literal("shopping"),
  v.literal("nightlife"),
  v.literal("nature"),
  v.literal("other"),
);

/** Editable activity fields (everything except ids, order and completion). */
export const activityFields = {
  title: v.string(),
  description: v.string(),
  address: v.string(),
  phone: v.optional(v.string()),
  photoUrl: v.string(),
  bookingUrl: v.optional(v.string()),
  websiteUrl: v.optional(v.string()),
  category: v.optional(activityCategory),
  /** Local time, "HH:mm" (24h). */
  startTime: v.optional(v.string()),
  durationMinutes: v.optional(v.number()),
  latitude: v.optional(v.number()),
  longitude: v.optional(v.number()),
  /** Rough cost per person in the trip's currency. */
  estimatedCost: v.optional(v.number()),
};

export const activityInput = v.object(activityFields);

export const subTripInput = v.object({
  title: v.string(),
  dayNumber: v.number(),
  /** ISO date "YYYY-MM-DD". */
  date: v.optional(v.string()),
  location: v.optional(v.string()),
  activities: v.array(activityInput),
});

/** A whole Trip -> SubTrip -> Activity tree, as seeded or generated by AI. */
export const tripTreeInput = v.object({
  title: v.string(),
  destination: v.string(),
  description: v.optional(v.string()),
  /** ISO dates "YYYY-MM-DD". */
  startDate: v.string(),
  endDate: v.string(),
  imageUrl: v.string(),
  currency: v.optional(v.string()),
  subTrips: v.array(subTripInput),
});

export type ActivityInput = Infer<typeof activityInput>;
export type SubTripInput = Infer<typeof subTripInput>;
export type TripTreeInput = Infer<typeof tripTreeInput>;
